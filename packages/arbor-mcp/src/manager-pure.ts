import { createHash } from "node:crypto";
import type { CampaignState, Provenance } from "@arbor/core";

/**
 * Stateless helpers for the campaign manager.
 *
 * These are deliberately pure: they carry no `this`-state coupling, so they are
 * trivially unit-testable in isolation and safe to move as the manager is
 * decomposed. Nothing here may reach into the ledger, persistence, or event
 * sink — that stateful wiring stays on the manager.
 */

/** Count visit_count across a campaign's nodes in the given category. */
export function countCategoryVisits(campaign: CampaignState, category: string): number {
  let count = 0;
  for (const node of campaign.tree.values()) {
    if (node.action.category === category) count += node.visit_count;
  }
  return count;
}

/**
 * KB findings are generated by the manager from a completed node, not written
 * verbatim by the Specialist. Preserve that distinction while binding the
 * derived finding to the exact result and Critic verdict.
 */
export function kbExtractionProvenance(
  campaignId: string,
  nodeId: string,
  params: {
    specialist_output: string;
    provenance: Provenance;
    critic_approved: boolean;
    critic_rationale: string;
    critic_root_cause?: string;
  },
): Extract<Provenance, { tag: "generated" }> {
  const input = JSON.stringify({
    campaign_id: campaignId,
    node_id: nodeId,
    specialist_output: params.specialist_output,
    specialist_provenance: params.provenance,
    critic_approved: params.critic_approved,
    critic_rationale: params.critic_rationale,
    critic_root_cause: params.critic_root_cause ?? null,
  });
  return {
    tag: "generated",
    generator: "campaign_manager.kb_extractor",
    input_hash: createHash("sha256").update(input).digest("hex"),
  };
}
