import { afterEach, describe, expect, it } from "vitest";
import { chmodSync, existsSync, mkdtempSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { computeEvidenceContentHashForStore, computeStoreDigest } from "../lib/store-provenance.mjs";

const roots = [];
const ROOT = join(import.meta.dirname, "..", "..");
const CLAIM_LEDGER_LIBRARY_IMPORT = Symbol.for("revoy2.claim-ledger.library-import");

async function loadNormalizer() {
  globalThis[CLAIM_LEDGER_LIBRARY_IMPORT] = true;
  try {
    return await import("../claim-ledger.ts");
  } finally {
    delete globalThis[CLAIM_LEDGER_LIBRARY_IMPORT];
  }
}

afterEach(() => { while (roots.length) rmSync(roots.pop(), { recursive: true, force: true }); });

describe("claim-ledger atomic publication", () => {
  it("publishes changed claims with the producer-captured canonical source digest", async () => {
    const root = mkdtempSync(join(tmpdir(), "claim-ledger-atomic-"));
    roots.push(root);
    const store = join(root, "claims");
    mkdirSync(store);
    writeFileSync(join(store, "claims.jsonl"), '{"old":true}\n');
    writeFileSync(join(store, "manifest.json"), '{"content_hash":"sha256:old"}\n');
    writeFileSync(join(store, "claim-guard.sh"), "#!/usr/bin/env bash\nexit 0\n");
    chmodSync(join(store, "claim-guard.sh"), 0o755);

    const sourceContentHash = computeEvidenceContentHashForStore(ROOT, "claim-ledger");
    const { normalizeStore } = await loadNormalizer();
    const normalized = normalizeStore([], "fixture-head", sourceContentHash, store);
    normalized.commit();

    expect(readFileSync(join(store, "claims.jsonl"), "utf8")).toBe("");
    expect(JSON.parse(readFileSync(join(store, "manifest.json"), "utf8")).content_hash).toBe(sourceContentHash);
    expect(readFileSync(join(store, "claim-guard.sh"), "utf8")).toBe("#!/usr/bin/env bash\nexit 0\n");
    expect(statSync(join(store, "claim-guard.sh")).mode & 0o777).toBe(0o755);
    expect(existsSync(normalized.staging)).toBe(false);
  });

  it("records a digest of the store's OWN bytes, which gate:store-freshness recomputes", async () => {
    // `content_hash` covers decisions/, ROADMAP.md and packages/*/src — the
    // store's INPUTS. `.claim-ledger/` is excluded from its own input scope by
    // construction, so without a digest of the generated bytes a store whose
    // every row was fabricated still hashed clean.
    const root = mkdtempSync(join(tmpdir(), "claim-ledger-digest-"));
    roots.push(root);
    const store = join(root, "claims");
    mkdirSync(store);
    writeFileSync(join(store, "claim-guard.sh"), "#!/usr/bin/env bash\nexit 0\n");
    chmodSync(join(store, "claim-guard.sh"), 0o755);

    const { normalizeStore } = await loadNormalizer();
    const normalized = normalizeStore([], "fixture-head", "sha256:inputs", store);
    normalized.commit();

    const manifest = JSON.parse(readFileSync(join(store, "manifest.json"), "utf8"));
    expect(manifest.store_digest).toBe(computeStoreDigest(store));
    // Ancillary operator policy is part of "the store's own bytes" too.
    writeFileSync(join(store, "claims.jsonl"), '{"id":"fabricated"}\n');
    expect(computeStoreDigest(store)).not.toBe(manifest.store_digest);
    writeFileSync(join(store, "claims.jsonl"), "");
    writeFileSync(join(store, "claim-guard.sh"), "#!/usr/bin/env bash\nexit 1\n");
    expect(computeStoreDigest(store)).not.toBe(manifest.store_digest);
  });

  it("restores claims, manifest, and ancillary executable bytes when publication fails", async () => {
    const root = mkdtempSync(join(tmpdir(), "claim-ledger-atomic-"));
    roots.push(root);
    const store = join(root, "claims");
    mkdirSync(store);
    writeFileSync(join(store, "claims.jsonl"), '{"old":true}\n');
    writeFileSync(join(store, "manifest.json"), '{"content_hash":"sha256:old"}\n');
    writeFileSync(join(store, "claim-guard.sh"), "#!/usr/bin/env bash\nexit 0\n");
    chmodSync(join(store, "claim-guard.sh"), 0o755);

    const { normalizeStore } = await loadNormalizer();
    const normalized = normalizeStore([], "fixture-head", computeEvidenceContentHashForStore(ROOT, "claim-ledger"), store);
    rmSync(normalized.staging, { recursive: true, force: true }); // force failure after the old directory moves aside

    expect(() => normalized.commit()).toThrow();
    expect(readFileSync(join(store, "claims.jsonl"), "utf8")).toBe('{"old":true}\n');
    expect(readFileSync(join(store, "manifest.json"), "utf8")).toBe('{"content_hash":"sha256:old"}\n');
    expect(readFileSync(join(store, "claim-guard.sh"), "utf8")).toBe("#!/usr/bin/env bash\nexit 0\n");
    expect(statSync(join(store, "claim-guard.sh")).mode & 0o777).toBe(0o755);
  });
});
